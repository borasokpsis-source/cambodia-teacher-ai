export function resourceMatchesSubject(resource, subjectId) {
  return resource.subjects.includes('all') || resource.subjects.includes(subjectId);
}

export function getRecommendedOpenResources(subjectId, limit = 4) {
  return OPEN_EDUCATIONAL_RESOURCES.filter((resource) =>
    resourceMatchesSubject(resource, subjectId)
  ).slice(0, limit);
}
